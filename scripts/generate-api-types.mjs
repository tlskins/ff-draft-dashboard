import { mkdir, readFile, writeFile } from "node:fs/promises"
import { dirname, join, resolve } from "node:path"
import { pathToFileURL } from "node:url"
import openapiTS, { astToString } from "openapi-typescript"

const projectRoot = process.cwd()
const schemaPath = resolve(
  process.env.DRAFTY_OPENAPI_SCHEMA
    || join(projectRoot, "..", "ff-draft-dashboard-python-api", "openapi", "v1.json"),
)
const outputPath = join(projectRoot, "behavior", "api", "schema.d.ts")
const checkOnly = process.argv.includes("--check")

const ast = await openapiTS(pathToFileURL(schemaPath), {
  silent: true,
})
const generated = [
  "/**",
  " * Generated from the Drafty API OpenAPI v1 contract.",
  " * Run `npm run api:types` after changing the API schema.",
  " * Do not edit this file directly.",
  " */",
  astToString(ast).trim(),
  "",
].join("\n")

if (checkOnly) {
  let current
  try {
    current = await readFile(outputPath, "utf8")
  } catch {
    throw new Error(
      `Generated API types are missing at ${outputPath}. Run npm run api:types.`,
    )
  }

  if (current !== generated) {
    throw new Error(
      "Generated API types are stale. Run npm run api:types and commit the result.",
    )
  }
  console.log("Generated API types are current.")
} else {
  await mkdir(dirname(outputPath), { recursive: true })
  await writeFile(outputPath, generated, "utf8")
  console.log(`Generated ${outputPath}`)
}
